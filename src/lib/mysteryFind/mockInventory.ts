import type { MysteryCategoryId, MysteryEligibleListing } from './types'

function mk(
  id: string,
  cat: MysteryCategoryId,
  title: string,
  seller: string,
  sid: string,
  price: number,
  compare: number,
  img: string,
  rating: number,
  engage: number,
  listedDays: number,
  local: boolean,
): MysteryEligibleListing {
  const row: MysteryEligibleListing = {
    id,
    title,
    imageUrl: img,
    sellerId: sid,
    sellerDisplayName: seller,
    sellerRating: rating,
    compareAtCents: compare,
    priceCents: price,
    category: cat,
    listedAgoMs: listedDays * 86400000,
    engagementScore: engage,
    shipsLocalFast: local,
    status: 'active',
    sellerOnboarded: true,
    restricted: false,
  }
  return {
    ...row,
    mysteryFindEligible: true,
    mysteryMinPayoutCents: Math.floor(price * 0.58),
    mysteryRarityLane: cat === 'luxury' ? 'luxury' : 'standard',
    mysteryBoostPriority: 0.55,
    mysteryLuxuryEligible: cat === 'luxury',
    mysterySource: 'marketplace',
    circulationCount: 0,
  }
}

